import {test,expect} from '@playwright/test';
import {serveEditor} from './support/tvEditor';
import {readFileSync} from 'node:fs';
import {DEFAULT_TV_CONFIG,normalizeTvConfig} from '../src/tv/config';
test('shape, linked sizing, measured grid, snapping and persistence',async({page})=>{
 test.setTimeout(90000);await page.setViewportSize({width:1600,height:1000});
 const errors:string[]=[];page.on('pageerror',e=>errors.push(e.message));
 const c=JSON.parse(readFileSync('public/new-shul-catalog.json','utf8'));
 const d=c.designs.find(x=>x.id==='d_daily_air');
 const server=await serveEditor(page,{...structuredClone(DEFAULT_TV_CONFIG),...d.values});
 await page.goto('/e2e/harness/editor.html');await page.getByRole('tab',{name:'עיצוב',exact:true}).click();
 const layers=page.getByLabel('שכבות החלקים',{exact:true});
 await layers.getByRole('button',{name:'מילוי זמני תפילות',exact:true}).click();
 await page.getByLabel('צורת התיבה והמסגרת',{exact:true}).selectOption('circle');
 const board=page.getByTestId('elements-canvas');
 await expect(board.locator('[data-geometric-shape="circle"]')).toHaveCount(2);
 const width=page.getByRole('spinbutton',{name:'רוחב החלק',exact:true});await width.fill('20');await width.press('Enter');
 const turn=page.getByRole('spinbutton',{name:'סיבוב',exact:true});await turn.fill('10');await turn.press('Enter');
 await page.getByRole('switch',{name:'הצגת רשת ומידות',exact:true}).click();
 await page.getByLabel('מרווח הרשת',{exact:true}).selectOption('5');
 await expect(board.getByTestId('measurement-grid')).toBeVisible();
 await expect(page.getByTestId('element-measurements')).toContainText('1920');
 await turn.fill('0');await turn.press('Enter');
 const fill=d.values.elements.find(e=>e.name==='מילוי זמני תפילות');
 const node=board.locator('[data-element-id="'+fill.id+'"]');
 await node.scrollIntoViewIfNeeded();const rect=await node.boundingBox();
 await page.mouse.move(rect!.x+rect!.width*.1,rect!.y+rect!.height*.5);await page.mouse.down();await page.mouse.move(rect!.x+rect!.width*.1+27,rect!.y+rect!.height*.5+17,{steps:5});await page.mouse.up();
 await page.getByRole('button',{name:/שמור ושדר/}).first().click();await expect.poll(()=>server.writes()).toBeGreaterThan(0);
 const saved=normalizeTvConfig(server.saved());const frame=saved.elements.find(e=>e.name==='מסגרת זמני תפילות')!;const f=saved.elements.find(e=>e.id===fill.id)!;
 expect(f.x).toBe(frame.x);expect(f.y).toBe(frame.y);expect(frame.width/frame.height).toBeCloseTo(9/16);expect(f.x/5).toBeCloseTo(Math.round(f.x/5));expect(f.y/5).toBeCloseTo(Math.round(f.y/5));
 await page.reload();await page.getByRole('tab',{name:'עיצוב',exact:true}).click();await expect(board.locator('[data-geometric-shape="circle"]')).toHaveCount(2);
 await layers.getByRole('button',{name:/^מסגרת זמני תפילות/ }).click();await page.getByLabel('צורת התיבה והמסגרת',{exact:true}).selectOption('hexagon');await expect(board.locator('[data-geometric-shape="hexagon"]')).toHaveCount(2);
 await page.getByRole('switch',{name:'הצגת רשת ומידות',exact:true}).click();await board.screenshot({path:'../outputs/section-shapes-grid.png'});
 expect(errors).toEqual([]);
});
