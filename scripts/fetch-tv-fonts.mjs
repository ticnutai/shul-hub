#!/usr/bin/env node
/**
 * Downloads the board's fonts into public-tv/fonts so the TV app works offline.
 *
 * The TV boots after a power cut, often before the router is back. Loading the
 * fonts from Google at that moment fails and the board comes up in a fallback
 * face. Bundling them removes the dependency. Only the hebrew and latin
 * subsets are kept (numbers and Hebrew are all the board draws).
 *
 * All families are SIL Open Font License, which permits self-hosting.
 * Re-run after changing the families in src/tv/themes.ts:
 *   node scripts/fetch-tv-fonts.mjs
 */

import fs from "node:fs";
import path from "node:path";
import { fileURLToPath } from "node:url";

const root = path.resolve(path.dirname(fileURLToPath(import.meta.url)), "..");
const outDir = path.join(root, "public-tv", "fonts");

const CSS_URL =
  "https://fonts.googleapis.com/css2?family=Assistant:wght@400;600;700&family=David+Libre:wght@400;500;700&family=Frank+Ruhl+Libre:wght@500;700;900&family=Heebo:wght@400;500;700;800&family=Rubik:wght@500;700&family=Secular+One&display=swap";
const KEEP_SUBSETS = new Set(["hebrew", "latin"]);

// Google serves woff2 only to a browser it recognises.
const UA =
  "Mozilla/5.0 (Windows NT 10.0; Win64; x64) AppleWebKit/537.36 (KHTML, like Gecko) Chrome/130.0 Safari/537.36";

const css = await (await fetch(CSS_URL, { headers: { "User-Agent": UA } })).text();

// Blocks look like: /* hebrew */ @font-face { ... src: url(...) format('woff2'); ... }
const blocks = [...css.matchAll(/\/\*\s*([a-z-]+)\s*\*\/\s*(@font-face\s*\{[^}]+\})/g)];
if (blocks.length === 0) throw new Error("No @font-face blocks found - did Google change the response?");

fs.rmSync(outDir, { recursive: true, force: true });
fs.mkdirSync(outDir, { recursive: true });

let out = "/* Generated by scripts/fetch-tv-fonts.mjs - do not edit by hand. */\n";
let files = 0;
let bytes = 0;
for (const [, subset, block] of blocks) {
  if (!KEEP_SUBSETS.has(subset)) continue;
  const family = block.match(/font-family:\s*'([^']+)'/)[1];
  const weight = block.match(/font-weight:\s*(\d+)/)[1];
  const url = block.match(/url\((https:[^)]+\.woff2)\)/)[1];
  const file = `${family.replace(/\s+/g, "")}-${weight}-${subset}.woff2`;
  const data = Buffer.from(await (await fetch(url)).arrayBuffer());
  fs.writeFileSync(path.join(outDir, file), data);
  files += 1;
  bytes += data.length;
  out += `/* ${subset} */\n${block.replace(url, `./${file}`)}\n`;
}

fs.writeFileSync(path.join(outDir, "fonts.css"), out);
console.log(`saved ${files} font files (${(bytes / 1024).toFixed(0)} KB) + fonts.css to ${path.relative(root, outDir)}`);
